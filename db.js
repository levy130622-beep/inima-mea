const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const DATA_DIR = path.join(__dirname, 'data');
const DB_FILE = path.join(DATA_DIR, 'db.json');

// Ensure data directory exists
if (!fs.existsSync(DATA_DIR)) {
  fs.mkdirSync(DATA_DIR, { recursive: true });
}

const defaultData = {
  alerts: [],
  subscriptions: [],
  settings: {
    pin: 'inima123',
    girlfriendName: 'Inima Mea',
    boyfriendName: 'Iubitul Tău',
    boyfriendPhone: '',
    whatsappNumber: '',
    whatsappApiKey: '',
    telegramBotToken: '',
    telegramChatId: '',
    vapidKeys: null, // Will be generated by push-service if not set
  },
  logs: []
};

class Database {
  constructor() {
    this.data = this.load();
  }

  load() {
    try {
      if (fs.existsSync(DB_FILE)) {
        const raw = fs.readFileSync(DB_FILE, 'utf8');
        const parsed = JSON.parse(raw);
        return {
          ...defaultData,
          ...parsed,
          settings: { ...defaultData.settings, ...(parsed.settings || {}) }
        };
      }
    } catch (err) {
      console.error('Error loading db.json, initializing fresh data:', err);
    }
    const initial = JSON.parse(JSON.stringify(defaultData));
    this.saveDirect(initial);
    return initial;
  }

  saveDirect(data) {
    const tempFile = `${DB_FILE}.${Date.now()}.tmp`;
    fs.writeFileSync(tempFile, JSON.stringify(data, null, 2), 'utf8');
    fs.renameSync(tempFile, DB_FILE);
  }

  async save() {
    try {
      const tempFile = `${DB_FILE}.${Date.now()}.tmp`;
      await fs.promises.writeFile(tempFile, JSON.stringify(this.data, null, 2), 'utf8');
      await fs.promises.rename(tempFile, DB_FILE);
    } catch (err) {
      console.error('Error saving db.json:', err);
    }
  }

  // --- Alerts ---
  getAlerts(limit = 100) {
    return [...this.data.alerts].reverse().slice(0, limit);
  }

  getAlertById(id) {
    return this.data.alerts.find(a => a.id === id);
  }

  getLatestAlert() {
    if (this.data.alerts.length === 0) return null;
    return this.data.alerts[this.data.alerts.length - 1];
  }

  async addAlert({ type, title, message, note, urgency = 'high', ip = '' }) {
    const now = new Date();
    const alert = {
      id: 'alert_' + Date.now() + '_' + crypto.randomBytes(3).toString('hex'),
      type: type || 'emergency',
      title: title || '❤️ Am nevoie de tine!',
      message: message || 'Iubita ta are nevoie de tine acum!',
      note: note ? String(note).trim() : '',
      urgency,
      ip,
      createdAt: now.toISOString(),
      timestampFormatted: now.toLocaleString('ro-RO', {
        timeZone: 'Europe/Bucharest',
        hour: '2-digit',
        minute: '2-digit',
        day: '2-digit',
        month: 'long',
        year: 'numeric'
      }),
      timeOnly: now.toLocaleString('ro-RO', {
        timeZone: 'Europe/Bucharest',
        hour: '2-digit',
        minute: '2-digit'
      }),
      status: 'pending', // 'pending' | 'acknowledged'
      acknowledgedAt: null,
      replyMessage: null
    };

    this.data.alerts.push(alert);
    // Keep max 500 alerts
    if (this.data.alerts.length > 500) {
      this.data.alerts = this.data.alerts.slice(-500);
    }
    await this.save();
    return alert;
  }

  async acknowledgeAlert(id, replyMessage = 'Sunt aici, iubirea mea! ❤️') {
    const alert = this.data.alerts.find(a => a.id === id);
    if (!alert) return null;

    const now = new Date();
    alert.status = 'acknowledged';
    alert.acknowledgedAt = now.toISOString();
    alert.replyMessage = replyMessage;
    alert.ackTimeFormatted = now.toLocaleString('ro-RO', {
      timeZone: 'Europe/Bucharest',
      hour: '2-digit',
      minute: '2-digit'
    });

    await this.save();
    return alert;
  }

  async deleteAlert(id) {
    const initialLen = this.data.alerts.length;
    this.data.alerts = this.data.alerts.filter(a => a.id !== id);
    if (this.data.alerts.length !== initialLen) {
      await this.save();
      return true;
    }
    return false;
  }

  async clearAllAlerts() {
    this.data.alerts = [];
    await this.save();
  }

  // --- Subscriptions ---
  getSubscriptions() {
    return this.data.subscriptions;
  }

  async saveSubscription({ endpoint, keys, role = 'boyfriend_iphone', deviceName = 'iPhone', userAgent = '' }) {
    if (!endpoint || !keys) throw new Error('Invalid subscription data');

    // Remove existing subscription with same endpoint if present
    this.data.subscriptions = this.data.subscriptions.filter(s => s.endpoint !== endpoint);

    const subscription = {
      id: 'sub_' + Date.now() + '_' + crypto.randomBytes(3).toString('hex'),
      endpoint,
      keys,
      role, // 'boyfriend_iphone' or 'girlfriend'
      deviceName: deviceName || 'Dispozitiv',
      userAgent,
      createdAt: new Date().toISOString(),
      lastSuccess: null,
      failCount: 0
    };

    this.data.subscriptions.push(subscription);
    await this.save();
    return subscription;
  }

  async removeSubscription(endpoint) {
    const initialLen = this.data.subscriptions.length;
    this.data.subscriptions = this.data.subscriptions.filter(s => s.endpoint !== endpoint);
    if (this.data.subscriptions.length !== initialLen) {
      await this.save();
      return true;
    }
    return false;
  }

  async updateSubscriptionHealth(endpoint, success = true) {
    const sub = this.data.subscriptions.find(s => s.endpoint === endpoint);
    if (!sub) return;
    if (success) {
      sub.lastSuccess = new Date().toISOString();
      sub.failCount = 0;
    } else {
      sub.failCount = (sub.failCount || 0) + 1;
    }
    await this.save();
  }

  // --- Settings ---
  getSettings() {
    return this.data.settings;
  }

  async updateSettings(partial) {
    this.data.settings = { ...this.data.settings, ...partial };
    await this.save();
    return this.data.settings;
  }

  // --- Logs ---
  getLogs(limit = 100) {
    return [...this.data.logs].reverse().slice(0, limit);
  }

  async addLog(level, message, details = null) {
    const log = {
      id: 'log_' + Date.now(),
      timestamp: new Date().toISOString(),
      level, // 'info' | 'warn' | 'error'
      message,
      details
    };
    this.data.logs.push(log);
    if (this.data.logs.length > 200) {
      this.data.logs = this.data.logs.slice(-200);
    }
    await this.save();
    return log;
  }
}

module.exports = new Database();
